// The business catalogue: what the assistant knows about a trade before it
// knows the model. A FUNCTION is what a team steers whatever the company sells
// (finance, marketing…); a SECTOR is the company's trade (retail, banking…). A
// model declares one or more of each — a bank has a marketing team too.
//
// Each domain lists its ROLES: the meaning a column of the model can carry
// (`ecommerce.revenue`). A role has a kind, which says what kind of field may
// carry it: a `measure` role goes on a measure, `date` on a date dimension,
// `key` on an identifier (one row per thing), `dimension` on any other
// dimension. `required` marks the roles without which the domain's trames
// cannot be drawn at all. Labels are what the glossary shows; ids are what
// the server checks (Set.has) and what the prompt carries.

const D = (id, label, roles) => ({ id, label, roles: roles.map(([rid, rlabel, kind, required = false]) => ({ id: rid, label: rlabel, kind, required })) });

